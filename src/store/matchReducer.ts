import { getFormation } from '@/domain/formations';
import { applyTemplate, captureLayout, moveSlot, resetToFormation, resolveTemplate } from '@/domain/layout';
import { getTeam } from '@/domain/match';
import type { MatchInfoPatch } from '@/domain/match';
import { applyPattern } from '@/domain/patterns';
import type { PatternId } from '@/domain/patterns';
import {
  addPlayer,
  removePlayer,
  setLineupRole,
  setSlotPosition,
  updatePlayer,
} from '@/domain/squad';
import type { PlayerDraft, SquadResult } from '@/domain/squad';
import type {
  FormationRef,
  Id,
  LineupRole,
  Match,
  Officials,
  Point,
  PositionCode,
  Team,
  TeamSide,
} from '@/domain/types';

export type TeamPatch = Partial<Pick<Team, 'name' | 'coach'>>;

export const MAX_LAYOUT_NAME_LENGTH = 40;

/**
 * Actions are plain data. IDs are generated by the dispatcher (see
 * `useMatchActions`) so the reducer stays pure and deterministic.
 */
export type MatchAction =
  | { type: 'match/updateInfo'; patch: MatchInfoPatch }
  | { type: 'officials/update'; patch: Partial<Officials> }
  | { type: 'team/update'; side: TeamSide; patch: TeamPatch }
  | { type: 'player/add'; side: TeamSide; draft: PlayerDraft; playerId: Id }
  | { type: 'player/update'; side: TeamSide; playerId: Id; draft: PlayerDraft }
  | { type: 'player/remove'; side: TeamSide; playerId: Id }
  | { type: 'lineup/setRole'; side: TeamSide; playerId: Id; role: LineupRole }
  | { type: 'slot/setPosition'; side: TeamSide; slotId: Id; position: PositionCode }
  | { type: 'slot/move'; side: TeamSide; slotId: Id; point: Point }
  | { type: 'formation/apply'; side: TeamSide; formation: FormationRef }
  | { type: 'formation/reset'; side: TeamSide }
  | { type: 'layout/save'; side: TeamSide; layoutId: Id; name: string }
  | { type: 'layout/delete'; layoutId: Id }
  | { type: 'pattern/apply'; side: TeamSide; patternId: PatternId; idSeed: Id }
  | { type: 'drawings/clear' };

function withTeam(match: Match, side: TeamSide, team: Team): Match {
  return side === 'home' ? { ...match, home: team } : { ...match, away: team };
}

/** Rejected squad operations leave the match untouched. */
function applyResult(match: Match, side: TeamSide, result: SquadResult): Match {
  return result.ok ? withTeam(match, side, result.team) : match;
}

/** Saved layouts that are deleted fall back to the preset they were based on. */
function detachLayout(team: Team, layoutId: Id, fallback: FormationRef): Team {
  return team.formation.kind === 'saved' && team.formation.id === layoutId ? { ...team, formation: fallback } : team;
}

export function matchReducer(match: Match, action: MatchAction): Match {
  switch (action.type) {
    case 'match/updateInfo':
      return { ...match, ...action.patch };

    case 'officials/update':
      return { ...match, officials: { ...match.officials, ...action.patch } };

    case 'team/update':
      return withTeam(match, action.side, { ...getTeam(match, action.side), ...action.patch });

    case 'player/add':
      return applyResult(match, action.side, addPlayer(getTeam(match, action.side), action.draft, action.playerId));

    case 'player/update':
      return applyResult(
        match,
        action.side,
        updatePlayer(getTeam(match, action.side), action.playerId, action.draft),
      );

    case 'player/remove':
      return withTeam(match, action.side, removePlayer(getTeam(match, action.side), action.playerId));

    case 'lineup/setRole':
      return applyResult(
        match,
        action.side,
        setLineupRole(getTeam(match, action.side), action.playerId, action.role),
      );

    case 'slot/setPosition':
      return withTeam(
        match,
        action.side,
        setSlotPosition(getTeam(match, action.side), action.slotId, action.position),
      );

    case 'slot/move':
      return withTeam(match, action.side, moveSlot(getTeam(match, action.side), action.slotId, action.point));

    case 'formation/apply': {
      const template = resolveTemplate(action.formation, match.savedLayouts);
      if (!template) return match;
      const team = getTeam(match, action.side);
      return withTeam(match, action.side, applyTemplate(team, template, action.side, action.formation));
    }

    case 'formation/reset':
      return withTeam(
        match,
        action.side,
        resetToFormation(getTeam(match, action.side), action.side, match.savedLayouts),
      );

    case 'layout/save': {
      const name = action.name.trim().slice(0, MAX_LAYOUT_NAME_LENGTH);
      if (!name) return match;
      const team = getTeam(match, action.side);
      const baseFormation =
        team.formation.kind === 'preset'
          ? team.formation.id
          : (match.savedLayouts.find((l) => l.id === team.formation.id)?.baseFormation ?? '4-3-3');
      const layout = { id: action.layoutId, name, baseFormation, slots: captureLayout(team, action.side) };
      // The saving team now follows the saved layout, so "reset" restores it.
      const next = withTeam(match, action.side, { ...team, formation: { kind: 'saved', id: layout.id } });
      return { ...next, savedLayouts: [...match.savedLayouts, layout] };
    }

    case 'layout/delete': {
      const layout = match.savedLayouts.find((l) => l.id === action.layoutId);
      if (!layout) return match;
      const fallback: FormationRef = { kind: 'preset', id: getFormation(layout.baseFormation).id };
      return {
        ...match,
        home: detachLayout(match.home, layout.id, fallback),
        away: detachLayout(match.away, layout.id, fallback),
        savedLayouts: match.savedLayouts.filter((l) => l.id !== layout.id),
      };
    }

    case 'pattern/apply': {
      const team = getTeam(match, action.side);
      const applied = applyPattern(team, action.side, action.patternId, match.savedLayouts, action.idSeed);
      // Replace this team's earlier pattern arrows; keep everything else.
      const kept = match.drawings.filter((d) => d.source?.teamId !== team.id);
      return { ...withTeam(match, action.side, applied.team), drawings: [...kept, ...applied.drawings] };
    }

    case 'drawings/clear':
      return match.drawings.length === 0 ? match : { ...match, drawings: [] };
  }
}
